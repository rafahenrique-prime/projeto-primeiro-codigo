/**
 * PRIME CONTROL V1.4F — GPTMaker-native Story fallback routing contract.
 *
 * Policy decision only. Zero I/O, zero model calls, no customer text generation
 * and no connection to an agent's inbound/outbound message handlers.
 * The NATIVE GPTMaker training remains the authority for the actual wording.
 *
 * This module is a LAB *harness*: it MUST NOT be imported in the production
 * webhook or installed as an automatic reply path without a separate approval.
 */
export const NATIVE_STORY_PRINT_TRAINING='3F9C22DD0477D04D51EC72B5AF3F6A41'
export const NATIVE_STORY_CONFIDENCE_TRAINING='3F90779F309300BCD5BD426E229A42AC'
export const REAL_STORY_FINGERPRINT='e7724e511a7e661c68aadfd9'
export const ALLOWED_SCOPE='GABY_LAB_COMERCIAL'
const isObj=x=>x!=null&&typeof x==='object'&&!Array.isArray(x)

/**
 * SAFE DEMO CONTRACT:
 * - A Gemini estimate of 90% is not a calibrated probability.
 * - Native HIGH/MEDIUM/LOW labels are NOT derived from the raw Gemini score.
 * - An existing BLOCK from JEV cannot be overridden by Visual Match or text.
 * - Mere presence of a catalog candidate does not verify the exact model.
 * - Customer-facing language MUST be generated by GPTMaker's native training,
 *   not by a duplicate custom assistant.
 */
export function routeToNativeStoryTraining(s={}){
 const base={
  mode:'LAB_POLICY_PREVIEW_ONLY',
  route:'BLOCK',
  training_id:null,
  reason:'INVALID_INPUT',
  messages_sent:0,external_calls:0,vision_calls:0,jev_calls:0,catalog_calls:0,
  price_allowed:false,pix_allowed:false,stock_allowed:false,
  exact_product_assertion_allowed:false,
  intended_delivery:'NONE',
 }
 if(!isObj(s)||s.scope!==ALLOWED_SCOPE)
  return {...base,reason:'OUTSIDE_LAB_SCOPE'}
 if(s.context_status!=='FOUND'){
  return {...base,route:'GPTMAKER_NATIVE_DEFAULT',reason:'NO_VERIFIED_STORY_CONTEXT',
   intended_delivery:'GPTMAKER_NATIVE_ONLY'}
 }
 if(typeof s.story_fingerprint!=='string'||!/^([a-f0-9]{24})$/.test(s.story_fingerprint)){
  return {...base,route:'BLOCK',reason:'STORY_FINGERPRINT_INVALID'}
 }
 if(s.story_fingerprint!==REAL_STORY_FINGERPRINT){
  return {...base,route:'BLOCK',reason:'DIFFERENT_STORY_REQUIRES_OWN_CORRELATION'}
 }
 const fromScreenshot=s.media_source==='USER_UPLOADED_IMAGE'
 const verified=s.catalog?.status==='READ_ONLY_OK' &&
  s.catalog?.exact_sku_verified===true &&
  s.jev?.status==='ok'&&s.jev?.action==='ALLOW_AUTO' &&
  s.visual?.status==='STRONG_VISUAL_MATCH'&&s.visual?.choice==='C1'&&
  Number.isFinite(s.visual?.confidence)&&s.visual.confidence>=0.95
 if(verified){
  return {...base,
   route:'GPTMAKER_NATIVE_CONFIRMED_CATALOG',
   training_id:NATIVE_STORY_CONFIDENCE_TRAINING,
   reason:'ALL_INDEPENDENT_GATES_PASSED',
   intended_delivery:'NATIVE_GPTMAKER_AFTER_SEPARATE_INTEGRATION',
   exact_product_assertion_allowed:true,
   // An explicitly verified catalog SKU still does not validate a commercial
   // price, a payment condition or physical availability by itself.
   price_allowed:s.catalog?.price_verified===true,
   pix_allowed:false,
   stock_allowed:s.catalog?.physical_stock_verified===true,
  }
 }
 if(fromScreenshot){
  // Do NOT ask again for the picture that is already attached.
  // The existing native confidence guidance uses ONE useful clarification.
  return {...base,route:'GPTMAKER_NATIVE_SINGLE_DETAIL',
   training_id:NATIVE_STORY_CONFIDENCE_TRAINING,
   reason:'UPLOAD_PRESENT_BUT_EXACT_PRODUCT_UNCONFIRMED',
   intended_delivery:'NATIVE_GPTMAKER_AFTER_SEPARATE_INTEGRATION'}
 }
 return {...base,
  route:'GPTMAKER_NATIVE_REQUEST_STORY_PRINT',
  training_id:NATIVE_STORY_PRINT_TRAINING,
  reason:s.jev?.action==='BLOCK_ASSERTION'?'JEV_BLOCKS_MODEL_ASSERTION':
   'STORY_MODEL_NOT_CONFIRMED',
  intended_delivery:'NATIVE_GPTMAKER_AFTER_SEPARATE_INTEGRATION',
 }
}

// Four immutable proof scenarios: real outcomes + safety counterfactuals.
