export function simulateNativeFallbackScenarios(){
 const cases=V14F_CASES.map(x=>{
  const answer=routeToNativeStoryTraining(x.input)
  return {scenario:x.name,expected:x.expected,actual:answer.route,
   passed:answer.route===x.expected&&answer.messages_sent===0&&
    answer.external_calls===0&&answer.vision_calls===0&&answer.jev_calls===0&&
    answer.catalog_calls===0,training_id:answer.training_id,
   price_allowed:answer.price_allowed,exact_product_assertion_allowed:answer.exact_product_assertion_allowed}
 })
 return {ok:cases.every(x=>x.passed),
  mode:'PURE_LAB_SIMULATION',
  scenarios:cases,
  messages_sent:0,external_calls:0,vision_calls:0,jev_calls:0,catalog_calls:0,
  training_modified:false,gaby_official_modified:false,
  actual_gptmaker_response_tested:false}
}
